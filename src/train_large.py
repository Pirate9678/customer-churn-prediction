#!/usr/bin/env python3
"""Train the churn classifier at scale (1M+ rows).

Same modelling approach as src/train.py — RandomForestClassifier with the
hyperparameter shape found by the grid search on the 7k baseline
(max_depth ~15, min_samples_leaf small, balanced classes) — but adapted
for volume:

  * n_estimators=50, max_depth=12, min_samples_leaf=10, max_samples=0.5:
    bounds tree size and the per-tree sample so training time and the
    serialized model stay manageable at scale (see MODEL_PARAMS comment
    for the measured trade-off vs 100 trees).
  * float32 feature matrix: halves the memory of the 1M x ~45 dense
    matrix with no measurable accuracy cost.
  * n_jobs=-1: all CPUs.

No grid search here — a 3-fold search over this grid at 1M rows would
take hours; the hyperparameters transfer from the tuned baseline.

Usage:
    python3 src/train_large.py                       # data/telco_churn_large.csv
    python3 src/train_large.py --input data/other.csv --test-rows 100000

Artifacts (models/ is git-ignored; regenerate any time):
    models/random_forest_churn_large.pkl
    models/metrics_large.json
    models/feature_importance_large.png
"""

import argparse
import json
import os
import sys
import time
from datetime import date

import matplotlib

matplotlib.use("Agg")
import numpy as np
import pandas as pd
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import train_test_split

sys.path.insert(0, os.path.dirname(__file__))

from data_loader import TARGET_COLUMN, load_data, prepare_frame
from features import FEATURE_COLUMNS, build_preprocessor, get_feature_names, save_pickle
from train import evaluate, plot_feature_importances

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DEFAULT_DATA = os.path.join(ROOT, "data", "telco_churn_large.csv")
MODELS_DIR = os.path.join(ROOT, "models")

RANDOM_STATE = 42

# Transferred from the 7k grid search (best: max_depth=15, min_samples_leaf=2,
# class_weight='balanced'), tightened to bound cost at 1M rows.
# Optimised Nov 2026 (measured in benchmark/benchmark.py): 50 trees instead
# of 100 (fit 111.9s -> 49.5s, metrics unchanged: acc 0.7530 vs 0.7527,
# ROC-AUC 0.8252) and max_samples=0.5 (each tree sees a 500k-row bootstrap
# sample; combined fit 32.9s, acc 0.7523, ROC-AUC 0.8252 — all within
# 0.05 points of the 100-tree config). HistGradientBoosting was tested as
# an alternative: same fit time, but recall collapsed (0.45 vs 0.75), so
# it was rejected for this retention use-case.
MODEL_PARAMS = {
    "n_estimators": 50,
    "max_depth": 12,
    "min_samples_leaf": 10,
    "max_samples": 0.5,
    "class_weight": "balanced",
    "random_state": RANDOM_STATE,
    "n_jobs": -1,
}


def main(argv=None):
    parser = argparse.ArgumentParser(description="Train churn model at scale.")
    parser.add_argument("--input", default=DEFAULT_DATA)
    parser.add_argument("--test-rows", type=int, default=200_000,
                        help="Held-out test rows (default: 200000)")
    args = parser.parse_args(argv)

    os.makedirs(MODELS_DIR, exist_ok=True)
    t0 = time.perf_counter()

    df = prepare_frame(load_data(args.input))
    X = df[FEATURE_COLUMNS]
    y = df[TARGET_COLUMN]
    print(f"Loaded {len(df):,} rows "
          f"({time.perf_counter() - t0:.1f}s), churn_rate={y.mean():.4f}")

    test_size = args.test_rows / len(df)
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=test_size, random_state=RANDOM_STATE, stratify=y
    )
    print(f"train={len(X_train):,} test={len(X_test):,}")

    t1 = time.perf_counter()
    preprocessor = build_preprocessor()
    X_train_t = preprocessor.fit_transform(X_train).astype(np.float32)
    X_test_t = preprocessor.transform(X_test).astype(np.float32)
    feature_names = get_feature_names(preprocessor)
    print(f"Preprocessed to {X_train_t.shape[1]} features "
          f"({time.perf_counter() - t1:.1f}s)")

    t2 = time.perf_counter()
    model = RandomForestClassifier(**MODEL_PARAMS)
    model.fit(X_train_t, y_train)
    fit_s = time.perf_counter() - t2
    print(f"RandomForest fit complete in {fit_s:.1f}s "
          f"({len(X_train) / fit_s:,.0f} rows/s)")

    y_pred = model.predict(X_test_t)
    y_proba = model.predict_proba(X_test_t)[:, 1]
    metrics = evaluate(y_test, y_pred, y_proba)

    importances = model.feature_importances_
    top_idx = np.argsort(importances)[::-1][:10]
    top_features = [
        {"feature": feature_names[i], "importance": round(float(importances[i]), 4)}
        for i in top_idx
    ]

    payload = {
        "data_source": "Synthetic 1.2M-row telco churn dataset generated by "
                       "data/generate_large_dataset.py (seed=42), calibrated "
                       "on the real IBM Telco Customer Churn data — see README",
        "data_rows": int(len(df)),
        "train_rows": int(len(X_train)),
        "test_rows": int(len(X_test)),
        "random_state": RANDOM_STATE,
        "churn_rate_overall": round(float(y.mean()), 4),
        "model_params": {k: v for k, v in MODEL_PARAMS.items()},
        "fit_seconds": round(fit_s, 1),
        "test_metrics": metrics,
        "top_10_features": top_features,
        "trained_on": date.today().isoformat(),
        "model": "RandomForestClassifier (scikit-learn)",
        "note": "Hyperparameter shape transferred from the grid-searched "
                "7k baseline; depth/leaf tightened to bound cost at scale.",
    }

    save_pickle(preprocessor, os.path.join(MODELS_DIR, "preprocessor_large.pkl"))
    save_pickle(model, os.path.join(MODELS_DIR, "random_forest_churn_large.pkl"))
    with open(os.path.join(MODELS_DIR, "metrics_large.json"), "w") as f:
        json.dump(payload, f, indent=2)
    plot_feature_importances(
        feature_names, importances,
        os.path.join(MODELS_DIR, "feature_importance_large.png"),
    )

    print("=== Large-scale training complete ===")
    for k, v in metrics.items():
        if k != "confusion_matrix":
            print(f"test_{k}={v}")
    print(f"test_confusion_matrix={metrics['confusion_matrix']}")
    print("Top 5 features:")
    for item in top_features[:5]:
        print(f"  {item['feature']}: {item['importance']}")
    print(f"Total wall time: {time.perf_counter() - t0:.1f}s")
    print("Artifacts saved to models/")


if __name__ == "__main__":
    main()
